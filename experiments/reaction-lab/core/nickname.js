  '陽炎', '宵闇', '暁', '黄昏', '霜降り', '初霜', '時雨', '夕凪',
  '月影', '夜露', '川霧', '花曇り', '雪明かり', '白露', '寒月', '朧',
  // 剣術・気構え
  '一閃', '刹那', '影踏み', '柳生', '無明', '不知火', '雷光', '疾風',
  '静寂', '木枯らし', '山颪', '空蝉', '残心', '居合', '抜き身', '紙一重',
  '心眼', '先の先', '後の先', '太刀風', '鞘走り', '峰打ち', '無刀', '見切り',
